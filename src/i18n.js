export function t(key, ...args) {
  const dict = strings[state.lang] || strings.id;
  const v = dict[key];
  if (typeof v === "function") return v(...args);
  if (v == null) return key;
  return v;
}

export function locale() {
  return state.lang === "en" ? "en-US" : "id-ID";
}

export function greeting() {
  const h = new Date().getHours();
  if (h < 11) return t("app.greet.morning");
  if (h < 15) return t("app.greet.day");
  if (h < 18) return t("app.greet.evening");
  return t("app.greet.night");
}
